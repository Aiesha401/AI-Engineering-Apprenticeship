from typing import TypedDict, Annotated
from langgraph.graph.message import add_messages
from langchain_core.tools import tool
from langchain_core.messages import HumanMessage, AIMessage, ToolMessage
from langchain_openai import ChatOpenAI

from langgraph.graph import StateGraph, START, END

from dotenv import load_dotenv
import os

load_dotenv()

MODEL = "nvidia/nemotron-3-ultra-550b-a55b"

model = ChatOpenAI(
    model=MODEL,
    api_key=os.getenv("NVIDIA_API_KEY"),
    base_url="https://integrate.api.nvidia.com/v1",
    temperature=0.2
)

@tool
def get_inventory(product: str) -> str:
    """Get the current inventory quantity for a product."""

    inventory = {
        "iPhone 16": 42,
        "Samsung S24": 18,
        "MacBook Air": 9
    }

    return str(
        inventory.get(product, "Product not found")
    )


@tool
def get_total_revenue() -> str:
    """Get the total revenue generated by CommerceOps."""

    return "$68,931.00"

tools = [
    get_inventory,
    get_total_revenue
]

model_with_tools = model.bind_tools(tools)

class AgentState(TypedDict):
    messages: Annotated[list, add_messages]

{
    "messages": [
        HumanMessage(
            content="How many iPhone 16 units are in stock?"
        )
    ]
}

def call_model(state):
    response = model_with_tools.invoke(
        state["messages"]
    )

    return {
        "messages": [
            response
        ]
    }

tool_map = {
    tool.name: tool
    for tool in tools
}

def execute_tools(state):

    last_message = state["messages"][-1]

    tool_messages = []

    for tool_call in last_message.tool_calls:

        tool_name = tool_call["name"]
        tool_args = tool_call["args"]

        selected_tool = tool_map[tool_name]

        result = selected_tool.invoke(
            tool_args
        )

        tool_messages.append(
            ToolMessage(
                content=str(result),
                tool_call_id=tool_call["id"]
            )
        )

    return {
        "messages": tool_messages
    }

def route_after_model(state):

    last_message = state["messages"][-1]

    if last_message.tool_calls:
        return "tools"

    return "end"

graph = StateGraph(AgentState)

graph.add_node(
    "model",
    call_model
)

graph.add_node(
    "tools",
    execute_tools
)

graph.add_edge(
    START,
    "model"
)

graph.add_conditional_edges(
    "model",
    route_after_model,
    {
        "tools": "tools",
        "end": END
    }
)

graph.add_edge(
    "tools",
    "model"
)

app = graph.compile()

result = app.invoke({
    "messages": [
        HumanMessage(
            content="How many iPhone 16 units are in stock?"
        )
    ]
})

for message in result["messages"]:
    print(type(message).__name__)
    print(message.content)
    print()