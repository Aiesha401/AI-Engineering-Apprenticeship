from langchain_core.tools import tool
from langchain_openai import ChatOpenAI
from langchain_core.messages import HumanMessage, AIMessage
from langchain_core.prompts import ChatPromptTemplate
from dotenv import load_dotenv
import os

load_dotenv()

MODEL = "nvidia/nemotron-3-ultra-550b-a55b"

model = ChatOpenAI(
    model=MODEL,
    api_key=os.getenv("NVIDIA_API_KEY"),
    base_url="https://integrate.api.nvidia.com/v1",
    temperature=0.2
)

@tool
def get_inventory(product: str) -> str:
    """Get the current inventory quantity for a product."""
    inventory = {
        "iPhone 16": 42,
        "Samsung S24": 18,
        "MacBook Air": 9
    }

    return str(
        inventory.get(product, "Product not found")
    )

@tool
def get_total_revenue() -> str:
    """Get the total revenue generated by CommerceOps."""
    return "$68,931.00"

@tool
def get_top_product() -> str:
    """Get the product with the highest inventory."""
    return "iPhone 16"

tools = [
    get_inventory,
    get_total_revenue,
    get_top_product
]

model_with_tools = model.bind_tools(tools)

response = model_with_tools.invoke(
    "How many iPhone 16 units are in stock?"
)

for tool_call in response.tool_calls:

    if tool_call["name"] == "get_inventory":

        result = get_inventory.invoke(
            tool_call["args"]
        )

        print("Tool result:", result)

history = []

history.append(
    HumanMessage(
        content="My name is Rayhan."
    )
)

history.append(
    AIMessage(
        content="Nice to meet you, Rayhan."
    )
)

# for message in history:
#     print(type(message))
#     print(message.content)

prompt = ChatPromptTemplate.from_messages([
    (
        "system",
        "You are CommerceOps AI."
    ),
    (
        "placeholder",
        "{history}"
    ),
    (
        "human",
        "{question}"
    )
])

history = [
    HumanMessage(
        content="My favorite product is the iPhone 16."
    ),
    AIMessage(
        content="Got it."
    )
]

chain = prompt | model

response = chain.invoke({
    "history": history,
    "question": "What is my favorite product?"
})

print(response.content)


